//! `nodoka install` / `uninstall`: shell startup files, editor settings, background service.
//! Everything added is marked so it can be removed exactly.

use crate::config::{self, Config};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const PRELOAD: &str = include_str!("../preload/preload.cjs");
const MARK_START: &str = "# >>> nodoka >>>";
const MARK_END: &str = "# <<< nodoka <<<";
const EDITOR_MARK: &str = "// nodoka: don't watch generated folders";
pub const SERVICE: &str = "nodoka";

/// Thread/worker caps, applied only when the variable isn't set already. Each one can only lower
/// a tool's default parallelism, never raise it.
pub const CAPS: &[(&str, &str)] = &[
    ("CARGO_BUILD_JOBS", "Rust: cargo build jobs"),
    ("GOMAXPROCS", "Go: threads running Go code (go build, esbuild, hugo…)"),
    ("RAYON_NUM_THREADS", "Rust tools using rayon"),
    ("TOKIO_WORKER_THREADS", "Rust tools using tokio (rspack, uv…)"),
    ("TURBO_TASKS_AVAILABLE_PARALLELISM", "Next.js Turbopack"),
    ("ROLLDOWN_WORKER_THREADS", "Rolldown / Vite 7+"),
    ("PNPM_MAX_WORKERS", "pnpm install workers"),
    ("PYTHON_CPU_COUNT", "Python 3.13+: os.cpu_count() for pools, pytest-xdist…"),
    ("PYTEST_XDIST_AUTO_NUM_WORKERS", "pytest -n auto"),
    ("UV_CONCURRENT_BUILDS", "uv: parallel source builds"),
    ("BUNDLE_JOBS", "Bundler: parallel gem installs"),
    ("PARALLEL_WORKERS", "Rails: parallel test workers"),
    ("DOTNET_PROCESSOR_COUNT", ".NET: processor count seen by MSBuild and tests"),
];

fn home() -> PathBuf {
    PathBuf::from(std::env::var("HOME").expect("HOME is not set"))
}

/// Node 24 made V8's young generation 4× bigger (64 MB semi-spaces). 16 is Node 22's default:
/// same speed, less memory per Node process. Smaller machines get 8 so it never raises V8's own
/// (smaller) default there. Only the young generation: the heap limit is untouched.
fn semi_space_mb() -> u64 {
    if crate::sys::mem_bytes() >= 8 << 30 { 16 } else { 8 }
}

/// glibc gives each thread its own malloc arena (up to 8 per core); 2 is the usual fix for Ruby,
/// Python and other many-threaded programs. Linux only: macOS doesn't use glibc.
const ARENAS: &str = if cfg!(target_os = "linux") { "MALLOC_ARENA_MAX" } else { "" };

/// Bun keeps quotes as part of the path (`preload not found "\"…\""`: every Bun-built tool,
/// Claude Code included, refused to start), so the path goes in bare; a path with a space can't.
fn bun_line(pre: &Path, line: impl Fn(&str) -> String) -> String {
    let pre = pre.display().to_string();
    if pre.contains(char::is_whitespace) { String::new() } else { line(&format!("--preload={pre} --smol")) }
}

fn env_sh(dir: &Path, cpus: usize) -> String {
    let pre = dir.join("preload.cjs");
    let bin = dir.join("bin");
    let mut s = format!(
        "# Generated by `nodoka install`. Settings live in {cfg}.\n\
         if [ ! -e \"{off}\" ] && [ -z \"${{NODOKA_OFF:-}}\" ]; then\n\
         \x20 case \":$PATH:\" in *\":{bin}:\"*) ;; *) export PATH=\"{bin}:$PATH\" ;; esac\n\
         \x20 case \"${{NODE_OPTIONS:-}}\" in *nodoka/preload.cjs*) ;; *) export NODE_OPTIONS=\"--require=\\\"{pre}\\\" --max-semi-space-size={semi}${{NODE_OPTIONS:+ $NODE_OPTIONS}}\" ;; esac\n\
         {bun}\
         \x20 export NODOKA_CPUS=\"${{NODOKA_CPUS:-{cpus}}}\"\n",
        cfg = dir.join("config").display(),
        off = dir.join("off").display(),
        bin = bin.display(),
        pre = pre.display(),
        semi = semi_space_mb(),
        bun = bun_line(&pre, |opts| format!(
            "  case \"${{BUN_OPTIONS:-}}\" in *nodoka/preload.cjs*) ;; *) export BUN_OPTIONS=\"{opts}${{BUN_OPTIONS:+ $BUN_OPTIONS}}\" ;; esac\n"
        )),
    );
    for (var, _) in CAPS {
        s += &format!("  export {var}=\"${{{var}:-$NODOKA_CPUS}}\"\n");
    }
    if !ARENAS.is_empty() {
        s += &format!("  export {ARENAS}=\"${{{ARENAS}:-2}}\"\n");
    }
    s + "fi\n"
}

fn env_fish(dir: &Path, cpus: usize) -> String {
    let pre = dir.join("preload.cjs");
    let mut s = format!(
        "# Generated by `nodoka install`. Settings live in {cfg}.\n\
         if not test -e \"{off}\"; and test -z \"$NODOKA_OFF\"\n\
         \x20   contains -- \"{bin}\" $PATH; or set -gx PATH \"{bin}\" $PATH\n\
         \x20   string match -q '*nodoka/preload.cjs*' -- \"$NODE_OPTIONS\"; or set -gx NODE_OPTIONS (string trim -- \"--require=\\\"{pre}\\\" --max-semi-space-size={semi} $NODE_OPTIONS\")\n\
         {bun}\
         \x20   set -q NODOKA_CPUS; or set -gx NODOKA_CPUS {cpus}\n",
        cfg = dir.join("config").display(),
        off = dir.join("off").display(),
        bin = dir.join("bin").display(),
        pre = pre.display(),
        semi = semi_space_mb(),
        bun = bun_line(&pre, |opts| format!(
            "    string match -q '*nodoka/preload.cjs*' -- \"$BUN_OPTIONS\"; or set -gx BUN_OPTIONS (string trim -- \"{opts} $BUN_OPTIONS\")\n"
        )),
    );
    for (var, _) in CAPS {
        s += &format!("    set -q {var}; or set -gx {var} $NODOKA_CPUS\n");
    }
    if !ARENAS.is_empty() {
        s += &format!("    set -q {ARENAS}; or set -gx {ARENAS} 2\n");
    }
    s + "end\n"
}

/// Shell startup files that get one marked line sourcing env.sh.
fn rc_files() -> Vec<PathBuf> {
    let h = home();
    let shell = std::env::var("SHELL").unwrap_or_default();
    let mut v = Vec::new();
    // .zshenv is read by every zsh, including the non-interactive shells coding agents use
    if shell.ends_with("zsh") || h.join(".zshenv").exists() || h.join(".zshrc").exists() || cfg!(target_os = "macos") {
        v.push(h.join(".zshenv"));
    }
    for f in [".bashrc", ".bash_profile"] {
        if h.join(f).exists() || (f == ".bashrc" && shell.ends_with("bash")) {
            v.push(h.join(f));
        }
    }
    v
}

fn fish_file() -> Option<PathBuf> {
    let d = home().join(".config/fish");
    d.exists().then(|| d.join("conf.d/nodoka.fish"))
}

fn editor_settings() -> Vec<PathBuf> {
    let base =
        if cfg!(target_os = "macos") { home().join("Library/Application Support") } else { home().join(".config") };
    ["Code", "Cursor", "Code - Insiders", "Windsurf", "VSCodium", "Antigravity"]
        .iter()
        .map(|e| base.join(e).join("User/settings.json"))
        .filter(|p| p.exists())
        .collect()
}

pub fn install(cfg: &Config) -> Result<(), String> {
    let dir = config::dir();
    fs::create_dir_all(dir.join("bin")).map_err(|e| format!("create {}: {e}", dir.display()))?;
    let bin = dir.join("bin/nodoka");
    let me = std::env::current_exe().map_err(|e| e.to_string())?;
    if me != bin {
        let tmp = dir.join("bin/.nodoka.new");
        fs::copy(&me, &tmp)
            .and_then(|_| fs::rename(&tmp, &bin))
            .map_err(|e| format!("copy the program to {}: {e}", bin.display()))?;
    }
    fs::write(dir.join("preload.cjs"), PRELOAD).map_err(|e| e.to_string())?;
    fs::write(dir.join("env.sh"), env_sh(&dir, cfg.cpus)).map_err(|e| e.to_string())?;
    if !dir.join("config").exists() {
        fs::write(dir.join("config"), config::TEMPLATE).map_err(|e| e.to_string())?;
    }
    println!("✓ program, settings and Node preload in {}", dir.display());

    let line = format!("{MARK_START}\n[ -f \"{0}\" ] && . \"{0}\"\n{MARK_END}\n", dir.join("env.sh").display());
    for rc in rc_files() {
        let old = fs::read_to_string(&rc).unwrap_or_default();
        fs::write(&rc, strip_block(&old) + &line).map_err(|e| format!("update {}: {e}", rc.display()))?;
        println!("✓ new shells load it ({})", rc.display());
    }
    if let Some(f) = fish_file() {
        fs::create_dir_all(f.parent().unwrap()).ok();
        fs::write(&f, env_fish(&dir, cfg.cpus)).map_err(|e| e.to_string())?;
        println!("✓ new fish shells load it ({})", f.display());
    }

    for s in editor_settings() {
        let text = fs::read_to_string(&s).unwrap_or_default();
        if text.contains(EDITOR_MARK) {
            continue;
        }
        if text.contains("\"files.watcherExclude\"") {
            println!(
                "• {} already sets files.watcherExclude; consider adding \"**/node_modules/**\": true",
                s.display()
            );
            continue;
        }
        let entry = format!(
            "\n  {EDITOR_MARK}\n  \"files.watcherExclude\": {{ \"**/.git/objects/**\": true, \"**/.git/subtree-cache/**\": true, \"**/.hg/store/**\": true, \"**/node_modules/**\": true, \"**/.venv/**\": true, \"**/target/**\": true, \"**/vendor/bundle/**\": true, \"**/.next/**\": true, \"**/.nuxt/**\": true, \"**/.turbo/**\": true, \"**/.gradle/**\": true, \"**/.dart_tool/**\": true, \"**/_build/**\": true, \"**/deps/**\": true, \"**/.claude/worktrees/**\": true, \"**/.worktrees/**\": true }},"
        );
        let new = match text.find('{') {
            Some(i) => format!("{}{entry}{}", &text[..=i], &text[i + 1..]),
            None => format!("{{{}\n}}\n", entry.trim_end_matches(',')),
        };
        if fs::write(&s, new).is_ok() {
            println!("✓ editor stops watching node_modules, target, .venv… ({})", s.display());
        }
    }

    if std::env::var("NODOKA_NO_SERVICE").as_deref() == Ok("1") {
        println!("• skipped the background helper (NODOKA_NO_SERVICE=1); run `nodoka daemon` yourself");
    } else {
        start_service(&bin)?;
    }
    println!(
        "\nOpen a new terminal (and restart coding agents) to pick it up. `nodoka status` shows what it is doing."
    );
    Ok(())
}

fn strip_block(s: &str) -> String {
    match (s.find(MARK_START), s.find(MARK_END)) {
        (Some(a), Some(b)) if b > a => s[..a].to_string() + s[b + MARK_END.len()..].trim_start_matches('\n'),
        _ => s.to_string(),
    }
}

fn strip_editor_entry(s: &str) -> String {
    let mut out = Vec::new();
    let mut lines = s.lines().peekable();
    while let Some(l) = lines.next() {
        if l.trim() == EDITOR_MARK {
            if lines.peek().is_some_and(|n| n.trim_start().starts_with("\"files.watcherExclude\"")) {
                lines.next();
            }
            continue;
        }
        out.push(l);
    }
    out.join("\n") + if s.ends_with('\n') { "\n" } else { "" }
}

pub fn uninstall() {
    let dir = config::dir();
    if std::env::var("NODOKA_NO_SERVICE").as_deref() != Ok("1") {
        stop_service();
    }
    crate::daemon::recover(&dir.join("paused"));
    for rc in rc_files() {
        if let Ok(old) = fs::read_to_string(&rc) {
            if old.contains(MARK_START) {
                fs::write(&rc, strip_block(&old)).ok();
                println!("✓ removed from {}", rc.display());
            }
        }
    }
    if let Some(f) = fish_file().filter(|f| f.exists()) {
        fs::remove_file(&f).ok();
        println!("✓ removed {}", f.display());
    }
    for s in editor_settings() {
        if let Ok(text) = fs::read_to_string(&s) {
            if text.contains(EDITOR_MARK) {
                fs::write(&s, strip_editor_entry(&text)).ok();
                println!("✓ restored editor settings ({})", s.display());
            }
        }
    }
    // Shells that are already open still point NODE_OPTIONS here; keep a no-op preload so Node keeps
    // starting in them. Everything else goes.
    fs::write(dir.join("preload.cjs"), "// nodoka was uninstalled\n").ok();
    for f in ["env.sh", "bin/nodoka", "status", "paused", "off"] {
        fs::remove_file(dir.join(f)).ok();
    }
    println!("✓ nodoka removed. Your settings stay in {} in case you come back.", dir.join("config").display());
}

#[cfg(target_os = "macos")]
fn plist_path() -> PathBuf {
    home().join(format!("Library/LaunchAgents/{SERVICE}.plist"))
}

#[cfg(target_os = "macos")]
fn start_service(bin: &Path) -> Result<(), String> {
    let plist = plist_path();
    fs::create_dir_all(plist.parent().unwrap()).ok();
    fs::write(
        &plist,
        format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>{SERVICE}</string>
  <key>ProgramArguments</key><array><string>{}</string><string>daemon</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ProcessType</key><string>Interactive</string>
  <key>StandardOutPath</key><string>/dev/null</string>
  <key>StandardErrorPath</key><string>{}</string>
</dict></plist>
"#,
            bin.display(),
            config::dir().join("log").display()
        ),
    )
    .map_err(|e| e.to_string())?;
    let target = format!("gui/{}", crate::sys::uid());
    Command::new("launchctl").args(["bootout", &format!("{target}/{SERVICE}")]).output().ok();
    // bootout returns before the old helper has exited (it resumes what it paused first); until then
    // bootstrap is refused, so a reinstall or upgrade would leave nodoka off. Retry for up to 10s.
    let ok = (0..40).any(|i| {
        if i > 0 {
            std::thread::sleep(std::time::Duration::from_millis(250));
        }
        Command::new("launchctl")
            .args(["bootstrap", &target, &plist.display().to_string()])
            .output()
            .is_ok_and(|o| o.status.success())
    });
    if ok {
        println!("✓ background helper running; it starts again at login");
        Ok(())
    } else {
        Err(format!("could not start the background helper. Try: launchctl bootstrap {target} {}", plist.display()))
    }
}

#[cfg(target_os = "macos")]
fn stop_service() {
    Command::new("launchctl").args(["bootout", &format!("gui/{}/{SERVICE}", crate::sys::uid())]).output().ok();
    if fs::remove_file(plist_path()).is_ok() {
        println!("✓ background helper stopped and removed");
    }
}

#[cfg(target_os = "macos")]
pub fn service_running() -> bool {
    Command::new("launchctl")
        .args(["print", &format!("gui/{}/{SERVICE}", crate::sys::uid())])
        .output()
        .is_ok_and(|o| o.status.success())
}

#[cfg(target_os = "linux")]
fn unit_path() -> PathBuf {
    home().join(format!(".config/systemd/user/{SERVICE}.service"))
}

#[cfg(target_os = "linux")]
fn start_service(bin: &Path) -> Result<(), String> {
    let unit = unit_path();
    fs::create_dir_all(unit.parent().unwrap()).ok();
    fs::write(
        &unit,
        format!(
            "[Unit]\nDescription=nodoka: keeps the machine responsive while dev work runs\n\n\
             [Service]\nExecStart={}\nRestart=always\nRestartSec=2\n\n\
             [Install]\nWantedBy=default.target\n",
            format_args!("\"{}\" daemon", bin.display())
        ),
    )
    .map_err(|e| e.to_string())?;
    let systemctl =
        |args: &[&str]| Command::new("systemctl").arg("--user").args(args).output().is_ok_and(|o| o.status.success());
    if systemctl(&["daemon-reload"]) && systemctl(&["enable", "--now", SERVICE]) && systemctl(&["restart", SERVICE]) {
        println!("✓ background helper running (systemd user service); it starts again at login");
        Ok(())
    } else {
        println!(
            "• systemd user services aren't available here. Start the helper yourself, for example from your shell profile:\n    pgrep -u \"$USER\" -f 'nodoka daemon' >/dev/null || (nohup \"{}\" daemon >/dev/null 2>&1 &)",
            bin.display()
        );
        Ok(())
    }
}

#[cfg(target_os = "linux")]
fn stop_service() {
    Command::new("systemctl").args(["--user", "disable", "--now", SERVICE]).output().ok();
    if fs::remove_file(unit_path()).is_ok() {
        Command::new("systemctl").args(["--user", "daemon-reload"]).output().ok();
        println!("✓ background helper stopped and removed");
    }
}

#[cfg(target_os = "linux")]
pub fn service_running() -> bool {
    Command::new("systemctl").args(["--user", "is-active", "--quiet", SERVICE]).status().is_ok_and(|s| s.success())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rc_block_is_replaced_not_duplicated_and_removed_exactly() {
        let line = format!("{MARK_START}\n. x\n{MARK_END}\n");
        let once = strip_block("export A=1\n") + &line;
        let twice = strip_block(&once) + &line;
        assert_eq!(once, twice);
        assert_eq!(strip_block(&twice), "export A=1\n");
    }

    #[test]
    fn editor_entry_round_trips() {
        let original = "{\n  \"editor.fontSize\": 13\n}\n";
        let with = format!(
            "{{\n  {EDITOR_MARK}\n  \"files.watcherExclude\": {{ \"**/node_modules/**\": true }},{}",
            &original[1..]
        );
        assert_eq!(strip_editor_entry(&with), original);
    }

    #[test]
    fn env_scripts_only_fill_unset_variables() {
        let sh = env_sh(Path::new("/h/.nodoka"), 4);
        assert!(sh.contains("export CARGO_BUILD_JOBS=\"${CARGO_BUILD_JOBS:-$NODOKA_CPUS}\""));
        assert!(sh.contains("NODOKA_CPUS:-4"));
        assert!(sh.contains(" --max-semi-space-size=") && sh.contains(" --smol"));
        assert_eq!(sh.contains("MALLOC_ARENA_MAX=\"${MALLOC_ARENA_MAX:-2}\""), cfg!(target_os = "linux"));
        let fish = env_fish(Path::new("/h/.nodoka"), 4);
        assert!(fish.contains("set -q GOMAXPROCS; or set -gx GOMAXPROCS $NODOKA_CPUS"));
        assert!(fish.contains(" --max-semi-space-size=") && fish.contains(" --smol"));
    }

    #[test]
    fn bun_gets_a_preload_path_it_can_open() {
        let dir = std::env::temp_dir().join(format!("nodoka-env-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("preload.cjs"), "").unwrap();
        fs::write(dir.join("env.sh"), env_sh(&dir, 4)).unwrap();
        let out = Command::new("sh")
            .arg("-c")
            .arg(". \"$0/env.sh\"; printf %s \"$BUN_OPTIONS\"")
            .arg(&dir)
            .env_remove("BUN_OPTIONS")
            .env_remove("NODOKA_OFF")
            .output()
            .unwrap();
        let opts = String::from_utf8_lossy(&out.stdout).into_owned();
        // Bun splits on spaces and keeps quotes: the value after --preload= must be the file itself
        let path = opts.split(' ').find_map(|w| w.strip_prefix("--preload=")).unwrap_or_default();
        assert!(Path::new(path).is_file(), "Bun would look for {path:?} (BUN_OPTIONS={opts:?})");
        assert!(env_fish(&dir, 4).contains(&format!("--preload={} --smol", dir.join("preload.cjs").display())));
        assert!(!env_sh(Path::new("/h/my home/.nodoka"), 4).contains("BUN_OPTIONS"));
        fs::remove_dir_all(&dir).ok();
    }
}
